#!/usr/bin/env python3
"""
gen_python_tests.py — Generate bin/us_tests/test_python_hardcoded.c

Two modes per test:
  - .py + .py.exp present: exact output comparison
  - .py only:              no-crash check (exit != 127, no unhandled traceback)

Usage:
  python3 gen_python_tests.py [--dir thirdparty/python/tests/basics]
                              [--out bin/us_tests/test_python_hardcoded.c]
"""

import os
import sys
import argparse


def c_escape(data: bytes) -> str:
    out = []
    for b in data:
        if b == ord('"'):
            out.append('\\"')
        elif b == ord('\\'):
            out.append('\\\\')
        elif b == ord('\n'):
            out.append('\\n')
        elif b == ord('\r'):
            out.append('\\r')
        elif b == ord('\t'):
            out.append('\\t')
        elif 0x20 <= b < 0x7f:
            out.append(chr(b))
        else:
            out.append(f'\\x{b:02x}')
    return ''.join(out)


def collect(tests_dir: str):
    """
    Return sorted list of (name, py_bytes, exp_bytes_or_None).
    All .py files are included; exp_bytes is None when no .exp exists.
    """
    entries = []
    for fname in sorted(os.listdir(tests_dir)):
        if not fname.endswith('.py'):
            continue
        py_path  = os.path.join(tests_dir, fname)
        exp_path = os.path.join(tests_dir, fname + '.exp')
        with open(py_path, 'rb') as f:
            py_bytes = f.read()
        exp_bytes = None
        if os.path.isfile(exp_path):
            with open(exp_path, 'rb') as f:
                exp_bytes = f.read()
        entries.append((fname, py_bytes, exp_bytes))
    return entries


def generate(entries, out_path: str):
    n_exp    = sum(1 for _, _, e in entries if e is not None)
    n_noexp  = len(entries) - n_exp

    lines = []
    lines.append('/*')
    lines.append(' * test_python_hardcoded.c — AUTO-GENERATED by gen_python_tests.py')
    lines.append(' * DO NOT EDIT — re-run gen_python_tests.py to regenerate.')
    lines.append(' *')
    lines.append(f' * {n_exp} tests with exact output check (.py.exp present)')
    lines.append(f' * {n_noexp} tests with no-crash check only (no .exp)')
    lines.append(' *')
    lines.append(' * No-crash check: MicroPython exits 0 on clean run and raise SystemExit.')
    lines.append(' * Unhandled exceptions (ImportError, TypeError, etc.) exit 1.')
    lines.append(' * So exit code 0 == pass, exit code 1 == unhandled exception.')
    lines.append(' */')
    lines.append('')
    lines.append('#include "us_test_common.h"')
    lines.append('#include <fcntl.h>')
    lines.append('#include <string.h>')
    lines.append('#include <unistd.h>')
    lines.append('#include <stdlib.h>')
    lines.append('#include <sys/wait.h>')
    lines.append('#include <stdio.h>')
    lines.append('')
    lines.append('#define HC_BUF_SIZE  65536')
    lines.append('#define PYTHON_BIN   "/bin/python"')
    lines.append('#define TMP_PY_PATH  "/tmp/_hc_test.py"')
    lines.append('')
    lines.append('typedef struct {')
    lines.append('    const char *name;')
    lines.append('    const char *py;')
    lines.append('    const char *exp;    /* NULL → no-crash mode */')
    lines.append('    size_t      exp_len;')
    lines.append('} hc_test_t;')
    lines.append('')

    # Emit py source strings
    for i, (name, py_bytes, _) in enumerate(entries):
        lines.append(f'static const char hc_py_{i}[] = "{c_escape(py_bytes)}";')

    lines.append('')

    # Emit exp strings only for paired tests
    for i, (name, _, exp_bytes) in enumerate(entries):
        if exp_bytes is not None:
            lines.append(f'static const char hc_exp_{i}[] = "{c_escape(exp_bytes)}";')

    lines.append('')

    # Table
    lines.append('static const hc_test_t hc_tests[] = {')
    for i, (name, _, exp_bytes) in enumerate(entries):
        if exp_bytes is not None:
            lines.append(f'    {{ "{name}", hc_py_{i}, hc_exp_{i}, {len(exp_bytes)}UL }},')
        else:
            lines.append(f'    {{ "{name}", hc_py_{i}, NULL, 0 }},')
    lines.append('};')
    lines.append(f'static const int hc_test_count = {len(entries)};')
    lines.append('')

    # hc_run_py: returns bytes captured, sets *exit_code
    lines.append(r"""
/* Write src to /tmp/_hc_test.py, run /bin/python, capture stdout+stderr.
 * Sets *wstatus to the raw waitpid status (use WIFEXITED/WEXITSTATUS).
 * Returns -1 on fork/pipe setup failure. */
static ssize_t hc_run_py(const char *src, char *out_buf, size_t buf_sz, int *wstatus)
{
    int fd = open(TMP_PY_PATH, O_WRONLY | O_CREAT | O_TRUNC, 0755);
    if (fd < 0) return -1;
    const char *shebang = "#!bin/python\n";
    write(fd, shebang, strlen(shebang));
    write(fd, src, strlen(src));
    close(fd);

    int pipefd[2];
    if (pipe(pipefd) < 0) return -1;

    pid_t pid = fork();
    if (pid < 0) { close(pipefd[0]); close(pipefd[1]); return -1; }

    if (pid == 0) {
        close(pipefd[0]);
        if (pipefd[1] != STDOUT_FILENO) {
            dup2(pipefd[1], STDOUT_FILENO);
            close(pipefd[1]);
        }
        dup2(STDOUT_FILENO, STDERR_FILENO);
        char *av[] = { (char *)PYTHON_BIN, (char *)TMP_PY_PATH, NULL };
        execve(PYTHON_BIN, av, NULL);
        _exit(127);
    }

    close(pipefd[1]);
    ssize_t total = 0, n;
    while (total < (ssize_t)buf_sz &&
           (n = read(pipefd[0], out_buf + total, buf_sz - (size_t)total)) > 0)
        total += n;
    close(pipefd[0]);

    *wstatus = 0;
    waitpid(pid, wstatus, 0);
    return total;
}
""")

    lines.append(r"""
void run_test_python_hardcoded(us_test_group_t *group)
{
    ut_group_begin(group, "python_hardcoded (basics embedded)");

    static char got[HC_BUF_SIZE];

    for (int i = 0; i < hc_test_count; i++) {
        const hc_test_t *t = &hc_tests[i];
        int exit_status = 0;

        ssize_t got_len = hc_run_py(t->py, got, sizeof(got) - 1, &exit_status);
        if (got_len < 0) {
            printf("  [FAIL] %s: fork/exec setup failed\n", t->name);
            group->failed++;
            ut_group_end(group);
            exit(1);
        }
        got[got_len] = '\0';

        /* exec itself failed — /bin/python not found */
        if (WIFEXITED(exit_status) && WEXITSTATUS(exit_status) == 127) {
            printf("  [FAIL] %s: execve /bin/python returned 127\n", t->name);
            group->failed++;
            ut_group_end(group);
            exit(1);
        }

        /* MicroPython SKIP signal */
        if (got_len >= 4 && strncmp(got, "SKIP", 4) == 0) {
            SKIP(group, t->name, "micropython printed SKIP");
            continue;
        }

        if (t->exp != NULL) {
            /* ── exact output comparison ── */
            int pass = ((size_t)got_len == t->exp_len &&
                        memcmp(got, t->exp, (size_t)got_len) == 0);
            TEST(group, t->name, pass);
            if (!pass) {
                size_t show = t->exp_len < 360 ? t->exp_len : 360;
                printf("  expected (%zu bytes): ", t->exp_len);
                fwrite(t->exp, 1, show, stdout);
                printf("%s\n", t->exp_len > 360 ? "..." : "");
                show = (size_t)got_len < 360 ? (size_t)got_len : 360;
                printf("  got      (%zd bytes): ", got_len);
                fwrite(got, 1, show, stdout);
                printf("%s\n", got_len > 360 ? "..." : "");
                ut_group_end(group);
                exit(1);
            }
        } else {
            /* ── no-crash check ──
             * MicroPython exits 0 for clean runs and raise SystemExit.
             * Unhandled exceptions (ImportError, TypeError, etc.) exit 1.
             * 127 means execve failed (python binary missing) — caught above. */
            int exit_code = WIFEXITED(exit_status) ? WEXITSTATUS(exit_status) : -1;
            int pass = (exit_code == 0);
            TEST(group, t->name, pass);
            if (!pass) {
                printf("  [no-exp] exit code %d", exit_code);
                if (got_len > 0) {
                    size_t show = (size_t)got_len < 480 ? (size_t)got_len : 480;
                    printf(", output:\n    ");
                    fwrite(got, 1, show, stdout);
                    printf("%s", got_len > 480 ? "..." : "");
                }
                printf("\n");
                ut_group_end(group);
                exit(1);
            }
        }
    }

    ut_group_end(group);
}
""")

    with open(out_path, 'w') as f:
        f.write('\n'.join(lines))
    print(f"wrote {len(entries)} tests ({n_exp} exp-backed, {n_noexp} no-crash) → {out_path}")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--dir', default='thirdparty/python/tests/basics',
                   help='directory containing .py and .py.exp files')
    p.add_argument('--out', default='bin/us_tests/test_python_hardcoded.c',
                   help='output .c file path')
    args = p.parse_args()

    script_dir = os.path.dirname(os.path.abspath(__file__))
    tests_dir  = os.path.join(script_dir, args.dir)
    out_path   = os.path.join(script_dir, args.out)

    if not os.path.isdir(tests_dir):
        print(f"error: tests dir not found: {tests_dir}", file=sys.stderr)
        sys.exit(1)

    entries = collect(tests_dir)
    if not entries:
        print(f"warning: no .py files found in {tests_dir}", file=sys.stderr)
        sys.exit(0)

    generate(entries, out_path)


if __name__ == '__main__':
    main()
